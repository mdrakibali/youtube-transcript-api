export {};

process.env.NODE_ENV = 'test';
process.env.API_KEY = 'test-secret-key';

const { default: app } = await import('../src/index.js');

interface TestResult {
  name: string;
  category: string;
  input: string;
  expectedStatus: number;
  actualStatus: number;
  expectedCode?: string;
  actualCode?: string;
  durationMs: number;
  passed: boolean;
  notes: string;
}

async function runTest(
  name: string,
  category: string,
  path: string,
  expectedStatus: number,
  expectedCode?: string,
  extraValidate?: (data: any) => string | null,
  customHeaders?: Record<string, string>
): Promise<TestResult> {
  const startTime = Date.now();
  let actualStatus = 0;
  let actualCode: string | undefined;
  let passed = false;
  let notes = '';

  try {
    const headers = customHeaders ?? { 'x-api-key': 'test-secret-key' };
    const res = await app.request(path, {
      method: 'GET',
      headers
    });

    actualStatus = res.status;
    const body: any = await res.json();
    actualCode = body.error;

    const statusMatch = actualStatus === expectedStatus;
    const codeMatch = !expectedCode || actualCode === expectedCode;

    let extraErr: string | null = null;
    if (statusMatch && extraValidate) {
      extraErr = extraValidate(body);
    }

    if (statusMatch && codeMatch && !extraErr) {
      passed = true;
      notes = body.selected
        ? `Lang: ${body.selected.code} (${body.selected.reason}, auto: ${body.selected.isAutoGenerated}) | ${body.transcript?.length} segments`
        : body.message || body.status || 'OK';
    } else {
      passed = false;
      notes = extraErr || `Expected status ${expectedStatus} (${expectedCode || 'any'}), got ${actualStatus} (${actualCode || 'none'})`;
    }
  } catch (err: any) {
    passed = false;
    notes = `Exception: ${err.message}`;
  }

  const durationMs = Date.now() - startTime;
  return {
    name,
    category,
    input: path,
    expectedStatus,
    actualStatus,
    expectedCode,
    actualCode,
    durationMs,
    passed,
    notes
  };
}

async function runAllTests() {
  console.log('\n========================================================================');
  console.log('                 YOUTUBE TRANSCRIPT API TEST SUITE');
  console.log('========================================================================\n');

  const results: TestResult[] = [];

  // Case 1: Manual captions (Rick Astley - Never Gonna Give You Up)
  results.push(
    await runTest(
      'Case 1: Manual captions',
      'manual captions',
      '/api/video?url=dQw4w9WgXcQ',
      200,
      undefined,
      (data) => {
        if (!data.metadata?.title) return 'Missing video title';
        if (!Array.isArray(data.transcript) || data.transcript.length === 0) return 'No transcript segments';
        if (data.selected?.isAutoGenerated !== false) return 'Expected manual caption track';
        if (!data.fullText) return 'Missing fullText';
        return null;
      }
    )
  );

  // Case 2: Auto-generated only (Psy - Gangnam Style)
  results.push(
    await runTest(
      'Case 2: Auto-generated only',
      'auto-generated only',
      '/api/video?url=https://www.youtube.com/watch?v=9bZkp7q19f0',
      200,
      undefined,
      (data) => {
        if (!Array.isArray(data.transcript) || data.transcript.length === 0) return 'No transcript segments';
        if (data.selected?.isAutoGenerated !== true) return 'Expected auto-generated caption track';
        return null;
      }
    )
  );

  // Case 3: No captions (Public video without captions)
  results.push(
    await runTest(
      'Case 3: No captions',
      'no captions',
      '/api/video?url=avtI0I09mgo',
      404,
      'NO_CAPTIONS'
    )
  );

  // Case 4: Non-English video with requested language (Despacito, lang=es)
  results.push(
    await runTest(
      'Case 4: Non-English video',
      'non-English video',
      '/api/video?url=https://youtu.be/kJQP7kiw5Fk&lang=es&format=text-timestamps',
      200,
      undefined,
      (data) => {
        if (data.selected?.code !== 'es' && !data.selected?.code?.startsWith('es-')) {
          return `Expected Spanish ("es"), got ${data.selected?.code}`;
        }
        if (data.selected?.reason !== 'requested') {
          return `Expected reason "requested", got ${data.selected?.reason}`;
        }
        if (!data.fullText.includes('[')) {
          return 'Expected format=text-timestamps to include bracketed timestamps in fullText';
        }
        return null;
      }
    )
  );

  // Case 5: Invalid input (Malformed URL or ID)
  results.push(
    await runTest(
      'Case 5: Invalid input',
      'invalid input',
      '/api/video?url=not_a_valid_youtube_video_id_or_url',
      400,
      'INVALID_URL'
    )
  );

  // Bonus 1: Health check (unauthenticated public route)
  results.push(
    await runTest(
      'Auth: Health Check (/health)',
      'health check',
      '/health',
      200,
      undefined,
      (data) => (data.status === 'ok' ? null : 'Expected status: "ok"'),
      {} // no x-api-key header
    )
  );

  // Bonus 2: Auth rejection (missing x-api-key on protected route)
  results.push(
    await runTest(
      'Auth: Missing API key',
      'auth rejection',
      '/api/video?url=dQw4w9WgXcQ',
      401,
      'UNAUTHORIZED',
      undefined,
      {} // no headers
    )
  );

  // Print Summary Table
  console.log('\n----------------------------------------------------------------------------------------------------------------------------------');
  console.log(
    '| ' +
      'Result'.padEnd(6) +
      ' | ' +
      'Case / Name'.padEnd(32) +
      ' | ' +
      'Status'.padEnd(8) +
      ' | ' +
      'Time'.padEnd(8) +
      ' | ' +
      'Details'.padEnd(62) +
      ' |'
  );
  console.log('----------------------------------------------------------------------------------------------------------------------------------');

  let allPassed = true;
  for (const r of results) {
    const icon = r.passed ? ' PASS ' : ' FAIL ';
    const statusStr = `${r.actualStatus}`;
    const timeStr = `${r.durationMs}ms`;
    const details = r.notes.length > 60 ? r.notes.slice(0, 59) + '…' : r.notes;

    if (!r.passed) allPassed = false;

    console.log(
      '| ' +
        icon.padEnd(6) +
        ' | ' +
        r.name.padEnd(32) +
        ' | ' +
        statusStr.padEnd(8) +
        ' | ' +
        timeStr.padEnd(8) +
        ' | ' +
        details.padEnd(62) +
        ' |'
    );
  }
  console.log('----------------------------------------------------------------------------------------------------------------------------------\n');

  if (allPassed) {
    console.log(` ALL TEST CASES PASSED SUCCESSFULLY!\n`);
    process.exit(0);
  } else {
    console.error(` SOME CASES FAILED. Check the output above.\n`);
    process.exit(1);
  }
}

runAllTests().catch((err) => {
  console.error('Test runner failure:', err);
  process.exit(1);
});

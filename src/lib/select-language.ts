import { AppError } from './errors.js';

export interface AvailableLanguage {
  code: string;
  name: string;
  isAutoGenerated: boolean;
  isTranslatable: boolean;
}

export type SelectionReason =
  | 'requested'
  | 'original'
  | 'fallback-en'
  | 'fallback-first';

export interface SelectedLanguage {
  code: string;
  name: string;
  isAutoGenerated: boolean;
  reason: SelectionReason;
}

function findTracksForCode(
  tracks: AvailableLanguage[],
  code: string
): AvailableLanguage[] {
  const norm = code.trim().toLowerCase();
  if (!norm) return [];

  // Exact match
  const exact = tracks.filter((t) => t.code.toLowerCase() === norm);
  if (exact.length > 0) return exact;

  // Language family match (e.g. "de" matches "de-DE", or "en-US" matches "en")
  return tracks.filter((t) => {
    const tCode = t.code.toLowerCase();
    return tCode.startsWith(`${norm}-`) || norm.startsWith(`${tCode}-`);
  });
}

function pickBestTrack(candidates: AvailableLanguage[]): AvailableLanguage {
  // Prefer manual track over auto-generated track for the same language
  const manual = candidates.find((t) => !t.isAutoGenerated);
  return manual || candidates[0];
}

/**
 * Selects the optimal caption language according to the rules:
 * 1. If lang is given, pick the first code that exists (preferring manual over auto-generated).
 * 2. Otherwise use the video's original language (infer from the auto-generated track's language,
 *    or the default/first manual track), preferring manual over auto-generated.
 * 3. If nothing matches, fall back to "en", then the first available track.
 * 4. If no captions exist at all, throws AppError(404, 'NO_CAPTIONS').
 */
export function selectLanguage(
  availableLanguages: AvailableLanguage[],
  langParam?: string
): SelectedLanguage {
  if (!availableLanguages || availableLanguages.length === 0) {
    throw new AppError(404, 'NO_CAPTIONS', 'No captions available for this video.');
  }

  // 1. If lang is given, evaluate comma-separated priority list
  if (langParam && langParam.trim().length > 0) {
    const requestedCodes = langParam
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);

    for (const code of requestedCodes) {
      const matches = findTracksForCode(availableLanguages, code);
      if (matches.length > 0) {
        const chosen = pickBestTrack(matches);
        return {
          code: chosen.code,
          name: chosen.name,
          isAutoGenerated: chosen.isAutoGenerated,
          reason: 'requested'
        };
      }
    }
  } else {
    // 2. Otherwise, use video's original language
    // Auto-generated caption track indicates the spoken language
    const autoTrack = availableLanguages.find((t) => t.isAutoGenerated);
    if (autoTrack) {
      const origMatches = findTracksForCode(availableLanguages, autoTrack.code);
      const chosen = pickBestTrack(origMatches);
      return {
        code: chosen.code,
        name: chosen.name,
        isAutoGenerated: chosen.isAutoGenerated,
        reason: 'original'
      };
    }

    // If no auto-generated track, take the first manual track
    const firstManual = availableLanguages.find((t) => !t.isAutoGenerated);
    if (firstManual) {
      return {
        code: firstManual.code,
        name: firstManual.name,
        isAutoGenerated: firstManual.isAutoGenerated,
        reason: 'original'
      };
    }
  }

  // 3. Fallback to English ("en")
  const enMatches = findTracksForCode(availableLanguages, 'en');
  if (enMatches.length > 0) {
    const chosenEn = pickBestTrack(enMatches);
    return {
      code: chosenEn.code,
      name: chosenEn.name,
      isAutoGenerated: chosenEn.isAutoGenerated,
      reason: 'fallback-en'
    };
  }

  // 4. Fallback to the first available track
  const firstTrack = availableLanguages[0];
  return {
    code: firstTrack.code,
    name: firstTrack.name,
    isAutoGenerated: firstTrack.isAutoGenerated,
    reason: 'fallback-first'
  };
}

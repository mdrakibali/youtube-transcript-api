import { Innertube } from 'youtubei.js';
import { AppError, mapErrorToAppError } from '../lib/errors.js';
import { formatTimestamp } from '../lib/format-timestamp.js';
import {
  selectLanguage,
  type AvailableLanguage,
  type SelectedLanguage
} from '../lib/select-language.js';
import {
  fetchFallbackTranscript,
  getFallbackLanguages,
  type NormalizedSegment
} from './fallback.js';

export interface VideoMetadata {
  title: string;
  channel: string;
  channelId: string;
  description: string;
  durationSeconds: number;
  publishedAt: string | null;
  viewCount: number;
  thumbnails: Array<{
    url: string;
    width?: number;
    height?: number;
  }>;
}

export interface VideoApiResponse {
  videoId: string;
  metadata: VideoMetadata;
  availableLanguages: AvailableLanguage[];
  selected: SelectedLanguage;
  transcript: Array<{
    text: string;
    startMs: number;
    durationMs: number;
    start: string;
  }>;
  fullText: string;
}

// Single lazy-loaded Innertube instance reused across requests
let innertubeInstance: Innertube | null = null;

export async function getInnertube(): Promise<Innertube> {
  if (!innertubeInstance) {
    innertubeInstance = await Innertube.create();
  }
  return innertubeInstance;
}

/**
 * Fetches video details, captions track list, and transcript.
 * Primary: youtubei.js (Innertube).
 * Fallback: youtube-transcript-plus (used only if youtubei.js fails to return a transcript).
 */
export async function getVideoData(
  videoId: string,
  langParam?: string,
  formatParam?: string
): Promise<VideoApiResponse> {
  const yt = await getInnertube();
  let info: any;

  try {
    info = await yt.getInfo(videoId);
  } catch (error) {
    throw mapErrorToAppError(error);
  }

  // Check playability
  if (info.playability_status && info.playability_status.status !== 'OK') {
    const reason = info.playability_status.reason || 'Video is unavailable';
    throw new AppError(404, 'VIDEO_UNAVAILABLE', reason);
  }

  const basic = info.basic_info;
  const metadata: VideoMetadata = {
    title: basic.title || '',
    channel: basic.author || '',
    channelId: basic.channel_id || '',
    description: basic.short_description || '',
    durationSeconds:
      typeof basic.duration === 'number'
        ? basic.duration
        : parseInt(String(basic.duration || 0), 10) || 0,
    publishedAt:
      basic.publish_date || (info.primary_info as any)?.published?.text || null,
    viewCount:
      typeof basic.view_count === 'number'
        ? basic.view_count
        : parseInt(String(basic.view_count || 0), 10) || 0,
    thumbnails: (basic.thumbnail || []).map((t: any) => ({
      url: t.url,
      width: t.width,
      height: t.height
    }))
  };

  // Build caption tracks from Innertube
  const rawTracks = info.captions?.caption_tracks || [];
  let availableLanguages: AvailableLanguage[] = rawTracks.map((t: any) => {
    const isAutoGenerated =
      t.kind === 'asr' ||
      (typeof t.vss_id === 'string' && t.vss_id.startsWith('a.'));
    const name =
      typeof t.name === 'string'
        ? t.name
        : t.name?.text || t.name?.toString?.() || t.language_code;
    return {
      code: t.language_code,
      name,
      isAutoGenerated,
      isTranslatable: Boolean(t.is_translatable)
    };
  });

  // If Innertube returned no tracks, attempt fallback listing
  if (availableLanguages.length === 0) {
    availableLanguages = await getFallbackLanguages(videoId);
  }

  if (availableLanguages.length === 0) {
    throw new AppError(404, 'NO_CAPTIONS', 'No captions available for this video.');
  }

  // Select language using the 4-step logic
  const selected = selectLanguage(availableLanguages, langParam);

  // Attempt transcript extraction: primary youtubei.js first
  let segments: NormalizedSegment[] | null = null;
  try {
    const transcriptInfo = await info.getTranscript();
    let targetTranscript = transcriptInfo;

    if (
      selected.name &&
      transcriptInfo.selectedLanguage &&
      selected.name !== transcriptInfo.selectedLanguage
    ) {
      try {
        targetTranscript = await transcriptInfo.selectLanguage(selected.name);
      } catch {
        // Keep initial transcript if language switch fails
      }
    }

    const initialSegments =
      targetTranscript.transcript?.content?.body?.initial_segments;
    if (Array.isArray(initialSegments) && initialSegments.length > 0) {
      segments = initialSegments
        .map((seg: any) => {
          const startMs = Math.max(0, parseInt(seg.start_ms, 10) || 0);
          const endMs = Math.max(startMs, parseInt(seg.end_ms, 10) || startMs);
          return {
            text: (seg.snippet?.toString?.() || seg.snippet?.text || '').trim(),
            startMs,
            durationMs: Math.max(0, endMs - startMs)
          };
        })
        .filter((s: NormalizedSegment) => s.text.length > 0);
    }
  } catch {
    // Primary extraction failed, fall back to youtube-transcript-plus
  }

  // Fallback to youtube-transcript-plus if primary failed or produced no segments
  if (!segments || segments.length === 0) {
    segments = await fetchFallbackTranscript(videoId, selected.code);
  }

  if (!segments || segments.length === 0) {
    throw new AppError(404, 'NO_CAPTIONS', 'No transcript content could be extracted for this video.');
  }

  // Format transcript segments
  const formattedTranscript = segments.map((seg) => ({
    text: seg.text,
    startMs: seg.startMs,
    durationMs: seg.durationMs,
    start: formatTimestamp(seg.startMs)
  }));

  // Build fullText
  let fullText: string;
  if (formatParam === 'text-timestamps') {
    fullText = formattedTranscript
      .map((s) => `[${s.start}] ${s.text}`)
      .join('\n');
  } else {
    fullText = formattedTranscript.map((s) => s.text).join(' ');
  }

  return {
    videoId,
    metadata,
    availableLanguages,
    selected,
    transcript: formattedTranscript,
    fullText
  };
}

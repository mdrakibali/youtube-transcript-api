import { Innertube, ClientType } from 'youtubei.js';
import { AppError } from '../lib/errors.js';
import { formatTimestamp } from '../lib/format-timestamp.js';
import {
  selectLanguage,
  type AvailableLanguage,
  type SelectedLanguage
} from '../lib/select-language.js';
import {
  fetchFallbackTranscript,
  getFallbackLanguages,
  type NormalizedSegment
} from './fallback.js';
import { fetchVideoMetadata, type VideoMetadata } from './metadata.js';
import { fetchSupadataTranscript } from './supadata.js';
import { fetchCapslaneTranscript } from './capslane.js';

export type { VideoMetadata };

export interface TranscriptApiResponse {
  videoId: string;
  provider: 'native' | 'supadata' | 'capslane';
  metadata: VideoMetadata;
  language: string;
  availableLanguages: string[];
  selected?: SelectedLanguage;
  transcript: Array<{
    text: string;
    start: string;
    startMs: number;
    durationMs: number;
  }>;
  fullText?: string;
}

import { HttpsProxyAgent } from 'https-proxy-agent';

function getProxyList(): string[] {
  const raw =
    process.env.YOUTUBE_PROXIES ||
    process.env.YOUTUBE_PROXY ||
    process.env.HTTP_PROXY ||
    '';
  return raw
    .split(',')
    .map((p) => p.trim())
    .filter(Boolean);
}

function getRandomProxy(): string | null {
  const list = getProxyList();
  if (list.length === 0) return null;
  return list[Math.floor(Math.random() * list.length)];
}

function maskProxy(proxyUrl: string | null): string {
  if (!proxyUrl) return 'Direct / No Proxy';
  try {
    const parsed = new URL(proxyUrl);
    return `${parsed.hostname}:${parsed.port}`;
  } catch {
    return 'Active Proxy';
  }
}

// Single lazy-loaded Innertube instance reused across requests
let innertubeInstance: Innertube | null = null;

async function getInnertube(): Promise<Innertube> {
  if (!innertubeInstance) {
    const cookie = process.env.YOUTUBE_COOKIE;
    const proxyList = getProxyList();

    let customFetch: typeof fetch | undefined = undefined;
    if (proxyList.length > 0) {
      customFetch = (url, init) => {
        const proxy = getRandomProxy();
        const agent = proxy ? new HttpsProxyAgent(proxy) : undefined;
        return fetch(url, {
          ...init,
          // @ts-ignore
          agent
        });
      };
    }

    console.log(
      `[Tier 1: Native] Initializing Innertube session (Proxy Pool: ${proxyList.length} proxies configured)`
    );

    innertubeInstance = await Innertube.create({
      fetch: customFetch
    });
  }
  return innertubeInstance;
}

/**
 * Directly downloads and parses YouTube's signed JSON3 timedtext track.
 */
async function fetchTimedTextSegments(
  baseUrl: string,
  proxyUrl?: string | null
): Promise<{ segments: NormalizedSegment[]; proxyUsed: string }> {
  const url = baseUrl.includes('fmt=')
    ? baseUrl.replace(/fmt=[^&]+/, 'fmt=json3')
    : `${baseUrl}&fmt=json3`;

  const cookie = process.env.YOUTUBE_COOKIE;
  const proxy = proxyUrl !== undefined ? proxyUrl : getRandomProxy();
  const hasCookie = Boolean(cookie && cookie.trim().length > 0);
  const maskedProxy = maskProxy(proxy);

  console.log(
    `[Tier 1: Native] 📡 TimedText Request -> Proxy: [${maskedProxy}] | Cookies: [${hasCookie ? 'YES' : 'NO'}]`
  );

  const headers: Record<string, string> = {
    'User-Agent':
      'com.google.android.youtube/20.10.38 (Linux; U; Android 14) gzip'
  };
  if (hasCookie) {
    headers['Cookie'] = cookie!.trim();
  }

  const fetchOptions: any = { headers };
  if (proxy) {
    fetchOptions.agent = new HttpsProxyAgent(proxy);
  }

  const res = await fetch(url, fetchOptions);

  if (!res.ok) {
    throw new Error(`Timedtext fetch failed with status ${res.status}`);
  }

  const data: any = await res.json();
  const events = data.events || [];

  const segments: NormalizedSegment[] = events
    .filter((e: any) => e.segs && e.segs.length > 0)
    .map((e: any) => {
      const text = e.segs.map((s: any) => s.utf8 || '').join('').trim();
      const startMs = Math.max(0, parseInt(String(e.tStartMs || 0), 10));
      const durationMs = Math.max(0, parseInt(String(e.dDurationMs || 0), 10));
      return {
        text,
        startMs,
        durationMs
      };
    })
    .filter((s: NormalizedSegment) => s.text.length > 0);

  return { segments, proxyUsed: maskedProxy };
}

/**
 * Fetches native transcript using youtubei.js (timedtext) or youtube-transcript-plus.
 */
async function fetchNativeTranscript(
  videoId: string,
  langParam?: string
): Promise<{
  segments: NormalizedSegment[];
  availableLanguages: AvailableLanguage[];
  selected: SelectedLanguage;
  proxyUsed: string;
} | null> {
  let proxyUsed = 'None';
  try {
    const yt = await getInnertube();
    const info = await yt.getBasicInfo(videoId, { client: ClientType.ANDROID });

    const rawTracks = info.captions?.caption_tracks || [];
    let availableLanguages: AvailableLanguage[] = rawTracks.map((t: any) => {
      const isAutoGenerated =
        t.kind === 'asr' ||
        (typeof t.vss_id === 'string' && t.vss_id.startsWith('a.'));
      const name =
        typeof t.name === 'string'
          ? t.name
          : t.name?.text || t.name?.toString?.() || t.language_code;
      return {
        code: t.language_code,
        name,
        isAutoGenerated,
        isTranslatable: Boolean(t.is_translatable)
      };
    });

    if (availableLanguages.length === 0) {
      availableLanguages = await getFallbackLanguages(videoId);
    }

    if (availableLanguages.length === 0) {
      return null;
    }

    const selected = selectLanguage(availableLanguages, langParam);

    // Try direct timedtext first
    let segments: NormalizedSegment[] | null = null;
    const matchingTrack =
      rawTracks.find(
        (t: any) => t.language_code.toLowerCase() === selected.code.toLowerCase()
      ) || rawTracks[0];

    if (matchingTrack?.base_url) {
      try {
        const timedTextResult = await fetchTimedTextSegments(matchingTrack.base_url);
        segments = timedTextResult.segments;
        proxyUsed = timedTextResult.proxyUsed;
      } catch (err: any) {
        console.warn(
          `[Tier 1: Native] ⚠️ TimedText fetch failed: ${err?.message || err}. Trying fallback library...`
        );
      }
    }

    // Try fallback library if timedtext failed
    if (!segments || segments.length === 0) {
      try {
        console.log(`[Tier 1: Native] Trying fallback library (youtube-transcript-plus)...`);
        segments = await fetchFallbackTranscript(videoId, selected.code);
        proxyUsed = 'Direct (fallback library)';
      } catch (err: any) {
        console.warn(`[Tier 1: Native] ⚠️ Fallback library failed: ${err?.message || err}`);
      }
    }

    if (!segments || segments.length === 0) {
      return null;
    }

    return {
      segments,
      availableLanguages,
      selected,
      proxyUsed
    };
  } catch (err: any) {
    console.warn(`[Tier 1: Native] ⚠️ Innertube getBasicInfo failed: ${err?.message || err}`);
    // If Innertube failed completely, try youtube-transcript-plus directly
    try {
      const fallbackLanguages = await getFallbackLanguages(videoId);
      if (fallbackLanguages.length === 0) return null;
      const selected = selectLanguage(fallbackLanguages, langParam);
      const segments = await fetchFallbackTranscript(videoId, selected.code);
      if (!segments || segments.length === 0) return null;
      return {
        segments,
        availableLanguages: fallbackLanguages,
        selected,
        proxyUsed: 'Direct (fallback library)'
      };
    } catch (fallbackErr: any) {
      console.warn(
        `[Tier 1: Native] ⚠️ Fallback library also failed: ${fallbackErr?.message || fallbackErr}`
      );
      return null;
    }
  }
}

/**
 * Main orchestrator:
 * 1. Fetches Video Metadata (Innertube + YouTube oEmbed fallback).
 * 2. Fetches Transcript using 3-Tier Fallback Chain:
 *    - Tier 1: Native (Innertube / youtube-transcript-plus)
 *    - Tier 2: Supadata AI API
 *    - Tier 3: Capslane API
 * 3. Conditionally appends fullText if includeFullText is true.
 */
export async function getVideoData(
  videoId: string,
  langParam?: string,
  includeFullText: boolean = false,
  formatParam?: string
): Promise<TranscriptApiResponse> {
  // 1. Fetch Video Metadata in parallel (guaranteed with oEmbed fallback)
  const metadataPromise = fetchVideoMetadata(videoId);

  let provider: 'native' | 'supadata' | 'capslane' = 'native';
  let segments: Array<{ text: string; start: string; startMs: number; durationMs: number }> = [];
  let language = langParam || 'en';
  let availableLanguages: string[] = [];
  let selected: SelectedLanguage | undefined = undefined;

function withTimeout<T>(promise: Promise<T>, ms: number, fallbackValue: T): Promise<T> {
  return Promise.race([
    promise,
    new Promise<T>((resolve) => setTimeout(() => resolve(fallbackValue), ms))
  ]);
}

  // --- Tier 1: Native Scraper (8s max timeout to prevent cloud hanging) ---
  const proxyList = getProxyList();
  const hasCookies = Boolean(
    process.env.YOUTUBE_COOKIE && process.env.YOUTUBE_COOKIE.trim().length > 0
  );
  console.log(
    `[Tier 1: Native] 🚀 Processing video: ${videoId} (Proxy Pool: ${proxyList.length} configured | Cookies: ${hasCookies ? 'ACTIVE' : 'NONE'})`
  );

  const nativeResult = await withTimeout(
    fetchNativeTranscript(videoId, langParam),
    8000,
    null
  );
  if (nativeResult && nativeResult.segments.length > 0) {
    provider = 'native';
    selected = nativeResult.selected;
    language = nativeResult.selected.code;
    availableLanguages = nativeResult.availableLanguages.map((l) => l.code);
    segments = nativeResult.segments.map((s) => ({
      text: s.text,
      start: formatTimestamp(s.startMs),
      startMs: s.startMs,
      durationMs: s.durationMs
    }));
    console.log(
      `[Tier 1: Native] ✅ SUCCESS: Got ${segments.length} segments (lang: ${language}) | Proxy: [${nativeResult.proxyUsed}] | Cookies: [${hasCookies ? 'ATTACHED' : 'NONE'}]`
    );
  } else {
    console.warn(`[Tier 1: Native] ⚠️ FAILED or timed out. Trying Tier 2 (Supadata)...`);
  }

  // --- Tier 2: Supadata API Fallback ---
  if (segments.length === 0) {
    console.log(`[Tier 2: Supadata] Calling Supadata API for video: ${videoId}`);
    const supadataResult = await fetchSupadataTranscript(videoId, langParam);
    if (supadataResult && supadataResult.segments.length > 0) {
      provider = 'supadata';
      language = supadataResult.language;
      availableLanguages = supadataResult.availableLanguages;
      segments = supadataResult.segments;
      console.log(`[Tier 2: Supadata] ✅ SUCCESS: Got ${segments.length} segments (lang: ${language})`);
    } else {
      console.warn(`[Tier 2: Supadata] ⚠️ FAILED or unavailable. Trying Tier 3 (Capslane)...`);
    }
  }

  // --- Tier 3: Capslane API Fallback ---
  if (segments.length === 0) {
    console.log(`[Tier 3: Capslane] Calling Capslane API for video: ${videoId}`);
    const capslaneResult = await fetchCapslaneTranscript(videoId, langParam);
    if (capslaneResult && capslaneResult.segments.length > 0) {
      provider = 'capslane';
      language = capslaneResult.language;
      availableLanguages = capslaneResult.availableLanguages;
      segments = capslaneResult.segments;
      console.log(`[Tier 3: Capslane] ✅ SUCCESS: Got ${segments.length} segments (lang: ${language})`);
    } else {
      console.error(`[Tier 3: Capslane] ❌ FAILED or unavailable.`);
    }
  }

  // If all 3 tiers failed to find transcripts
  if (segments.length === 0) {
    throw new AppError(
      404,
      'NO_CAPTIONS',
      'No captions or transcripts available for this video across all available providers.'
    );
  }

  const metadata = await metadataPromise;

  // If metadata duration was unavailable (e.g. from oEmbed), calculate from last segment
  if (metadata.durationSeconds === 0 && segments.length > 0) {
    const last = segments[segments.length - 1];
    metadata.durationSeconds = Math.round((last.startMs + last.durationMs) / 1000);
  }

  const response: TranscriptApiResponse = {
    videoId,
    provider,
    metadata,
    language,
    availableLanguages,
    transcript: segments
  };

  if (selected) {
    response.selected = selected;
  }

  // Append fullText only if requested or if legacy text-timestamps format was requested
  if (includeFullText || formatParam === 'text-timestamps') {
    if (formatParam === 'text-timestamps') {
      response.fullText = segments.map((s) => `[${s.start}] ${s.text}`).join('\n');
    } else {
      response.fullText = segments.map((s) => s.text).join(' ');
    }
  }

  return response;
}

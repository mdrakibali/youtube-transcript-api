import { fetchTranscript, listLanguages, YoutubeTranscript } from 'youtube-transcript-plus';
import { AppError, mapErrorToAppError } from '../lib/errors.js';
import type { AvailableLanguage } from '../lib/select-language.js';

export interface NormalizedSegment {
  text: string;
  startMs: number;
  durationMs: number;
}

export interface FallbackFullResult {
  metadata: {
    title: string;
    channel: string;
    channelId: string;
    description: string;
    durationSeconds: number;
    publishedAt: string | null;
    viewCount: number;
    thumbnails: Array<{ url: string; width?: number; height?: number }>;
  };
  availableLanguages: AvailableLanguage[];
  segments: NormalizedSegment[];
}

/**
 * Fetches transcript segments using youtube-transcript-plus as a fallback.
 * Strictly performs at most one attempt with no retry loops.
 */
export async function fetchFallbackTranscript(
  videoId: string,
  langCode?: string
): Promise<NormalizedSegment[]> {
  try {
    const rawSegments = await fetchTranscript(
      videoId,
      langCode ? { lang: langCode } : undefined
    );

    if (!rawSegments || rawSegments.length === 0) {
      throw new AppError(404, 'NO_CAPTIONS', 'No transcript segments returned from fallback source.');
    }

    return rawSegments.map((segment: { text: string; offset: number; duration: number }) => ({
      text: segment.text,
      startMs: Math.max(0, Math.round((segment.offset || 0) * 1000)),
      durationMs: Math.max(0, Math.round((segment.duration || 0) * 1000))
    }));
  } catch (error) {
    throw mapErrorToAppError(error);
  }
}

/**
 * Lists available caption languages from youtube-transcript-plus if primary provider found none.
 */
export async function getFallbackLanguages(videoId: string): Promise<AvailableLanguage[]> {
  try {
    const langs = await listLanguages(videoId);
    if (!langs || langs.length === 0) {
      return [];
    }

    return langs.map((l) => ({
      code: l.languageCode,
      name: l.languageName || l.languageCode,
      isAutoGenerated: Boolean(l.isAutoGenerated),
      isTranslatable: false
    }));
  } catch {
    return [];
  }
}

/**
 * Full fallback: retrieves both video metadata and transcript segments
 * when Innertube is blocked by cloud bot-detection ("Sign in to confirm you're not a bot").
 */
export async function fetchFallbackFull(
  videoId: string,
  langCode?: string
): Promise<FallbackFullResult> {
  try {
    const yt = new YoutubeTranscript({
      videoDetails: true,
      lang: langCode
    });
    const rawResult: any = await yt.fetchTranscript(videoId);

    const details = rawResult.videoDetails || {};
    const rawSegments = rawResult.segments || (Array.isArray(rawResult) ? rawResult : []);

    const languages = await getFallbackLanguages(videoId);

    const segments: NormalizedSegment[] = rawSegments.map(
      (segment: { text: string; offset: number; duration: number }) => ({
        text: segment.text,
        startMs: Math.max(0, Math.round((segment.offset || 0) * 1000)),
        durationMs: Math.max(0, Math.round((segment.duration || 0) * 1000))
      })
    );

    return {
      metadata: {
        title: details.title || '',
        channel: details.author || '',
        channelId: details.channelId || '',
        description: details.description || '',
        durationSeconds: parseInt(String(details.lengthSeconds || 0), 10) || 0,
        publishedAt: null,
        viewCount: parseInt(String(details.viewCount || 0), 10) || 0,
        thumbnails: (details.thumbnails || []).map((t: any) => ({
          url: t.url,
          width: t.width,
          height: t.height
        }))
      },
      availableLanguages: languages,
      segments
    };
  } catch (err) {
    throw mapErrorToAppError(err);
  }
}
